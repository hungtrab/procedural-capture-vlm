def split_parts(path, outdir, name, chunk=30 << 20):
    """md5 the adapter, and cut it into parts the Colab driver can download.

    Two separate jobs in one function, and only the second is transfer machinery. The md5
    is a correctness check: it is how a human tells an af adapter from a db one, and an af
    and a db adapter with the same md5 means the arm split failed and every number from the
    run is the same adapter twice (next_step.md, "the numbers are flat and identical across
    arms"). So it is computed and printed on both paths.

    MVLM_SPLIT=0 skips only the cutting. The 30MB parts exist because the Colab CLI cannot
    move a 300MB file in one download (run_mvlm.sh:215); on a shared filesystem the adapter
    is already where the next job will read it and splitting it just writes a second copy.

    An unreadable adapter is REPORTED here, never raised. Both jobs read `path`, so a file
    that is missing by the time this runs used to end the process in a FileNotFoundError
    traceback -- on the MVLM_SPLIT=0 path too, since the md5 is computed on both. The arm
    is lost either way, but a traceback buries the arms that did train, and the driver's
    own md5 check (run_cell.sh:509-517) already stops the cell with a sentence an operator
    can act on. Say which file and why, and let the loop finish.
    """
    i = 0
    try:
        if os.environ.get("MVLM_SPLIT", "1") != "0":
            os.makedirs(outdir, exist_ok=True)
            for old in glob.glob(f"{outdir}/{name}.p*"):
                os.remove(old)
            with open(path, "rb") as fh:
                while True:
                    b = fh.read(chunk)
                    if not b:
                        break
                    open(f"{outdir}/{name}.p{i:02d}", "wb").write(b)
                    i += 1
        h = hashlib.md5(open(path, "rb").read()).hexdigest()
    except OSError as e:
        print(f"  {name}: no md5 and no parts -- cannot read {path}: {e}", flush=True)
        print(f"    Nothing downstream can load this arm. Check whether {path} was "
              "deleted to reclaim space; resubmit and the arm is retrained from the first "
              "step.", flush=True)
        return
    print(f"  {name}: {i} parts, md5={h}", flush=True)


# ---------- when is an arm finished? ----------
# THE CONTRACT, and a driver must use the same one. An arm is finished when
#
#     <MVLM_ROOT>/adapter_<arm>/SAVE_OK
#
# exists. The file is small and non-empty, so a driver tests it with [ -f ] or [ -s ]; it is
# written LAST, after every weight file is in place, so its presence means the save completed
# and nothing else does.
#
# The old test -- the one in this script (os.path.exists) and the one in the driver
# ([ -s adapter_model.safetensors ]) -- cannot say that. model.save_pretrained writes
# adapter_model.safetensors in place and incrementally, and this partition runs with
# PreemptMode=REQUEUE, so a job can be killed at any instant including the middle of that
# write. What is left is a truncated but NON-EMPTY file that both tests accept. Training is
# then skipped forever; the two md5s still differ so section 3 of the driver passes; the
# benign gate fails on an adapter that is half a tensor; gate_ok.py exits 1; the cell is
# resubmitted and does exactly the same thing again. The only escape from that loop is
# deleting a directory, which AGENTS.md rule 2 tells the operator never to do.
#
# And the sentinel is necessary but NOT sufficient. It records that a save completed; it
# does not record that the result is still on the disk. An operator reclaiming space deletes
# the 300MB adapter_model.safetensors and leaves the two small files behind, and then
# SAVE_OK is true of a directory with no weights in it. So the test is the conjunction, here
# and in run_cell.sh:482-483 both: one predicate written twice, and the two must not drift.
SENTINEL = "SAVE_OK"


def _safetensors_complete(path):
    """Is this a whole safetensors file, or the front of one?

    The format is 8 bytes of little-endian header length, that many bytes of JSON, then the
    tensor buffer; every tensor records its [start, end) inside that buffer. So the size the
    file must have is computable from its own header, and a truncated file is detectable
    exactly, without torch and without reading the weights.

    This exists for adapters trained BEFORE the sentinel: they are complete and must not be
    retrained (AGENTS.md rule 2), but they have no SAVE_OK. Rather than trust their mere
    existence -- which is the test that let the truncated file through -- they are checked
    and then adopted.
    """
    try:
        size = os.path.getsize(path)
        with open(path, "rb") as fh:
            head = fh.read(8)
            if len(head) < 8:
                return False
            n = int.from_bytes(head, "little")
            if n <= 0 or 8 + n > size:
                return False
            hdr = json.loads(fh.read(n).decode("utf-8"))
    except (OSError, ValueError, UnicodeDecodeError):
        return False
    end = 0
    for k, v in hdr.items():
        if k == "__metadata__" or not isinstance(v, dict):
            continue
        off = v.get("data_offsets")
        if isinstance(off, (list, tuple)) and len(off) == 2:
            end = max(end, int(off[1]))
    return size == 8 + n + end


def _weights_bytes(path):
    """Size of adapter_model.safetensors, or -1 when it cannot be read at all.

    One test for the ways the weights can be absent -- deleted, or a store that will not
    open them -- because both mean the same thing to a caller: there is nothing here for
    the gate to load. A stat is not a read, so this opens the file; one byte costs nothing
    beside a 4-bit backbone load and it is the only way to tell a readable file from a
    directory entry.

    "readable and bigger than zero" is also exactly what run_cell.sh:482's
    `[ -s adapter_model.safetensors ]` means, which is the point: the driver's predicate
    and this one have to agree.
    """
    try:
        with open(path, "rb") as fh:
            fh.read(1)
        return os.path.getsize(path)
    except OSError:
        return -1


def _adapter_ready(outdir):
    """True when adapter_<arm>/ holds a finished adapter and training can be skipped.

    BOTH halves are required, which is the conjunction run_cell.sh:482-483 tests. The
    sentinel says a save completed; the weights say the result of that save is still on the
    disk. The sentinel ALONE used to be enough here, and the state where the two differ is
    an operator reclaiming space: adapter_model.safetensors deleted, SAVE_OK and
    adapter_config.json left behind. The driver read that correctly, decided "training" and
    launched this script -- which read the sentinel, printed "adapter already present,
    skipping", and fell straight into split_parts, which md5s the file that is not there.
    FileNotFoundError, on every resubmission, under MVLM_SPLIT=0 as well because the md5 is
    computed on both paths. A recoverable state -- retrain the arm, 17.5 minutes for two
    (run_mvlm.sh:27-34) -- had become a permanent failure.
    """
    w = f"{outdir}/adapter_model.safetensors"
    n = _weights_bytes(w)
    if os.path.exists(f"{outdir}/{SENTINEL}"):
        if n > 0:
            return True
        # Name both halves. Silence here reads as the resume guard misfiring, and that is
        # what invites the one repair AGENTS.md rule 2 forbids -- clearing the directory --
        # when retraining this one arm is the whole fix.
        print(f"  {outdir}/{SENTINEL} is present, so a save did complete, but {w} is "
              f"{'empty' if n == 0 else 'gone or unreadable'}: the weights are not on the "
              "disk any more, whatever the sentinel says. Retraining this arm.", flush=True)
        return False
    if n < 0:
        # No sentinel and no readable weights. An arm that has never been trained looks
        # exactly like this, so it is silent -- unless the name is there and the bytes are
        # not, which is a store problem and not a first run.
        if os.path.exists(w):
            print(f"  {w} exists but cannot be read; treating this arm as untrained and "
                  "retraining it.", flush=True)
        return False
    if not _safetensors_complete(w):
        # The exact failure described above. Say so: the alternative is a silent retrain
        # that looks like the resume guard misfiring.
        print(f"  {w} is {n} bytes and is NOT a complete safetensors "
              "file -- a save was interrupted. Retraining this arm.", flush=True)
        return False
    # Complete, but written before SAVE_OK existed. Adopt it.
    _mark_saved(outdir, f"adopted: complete adapter_model.safetensors found with no "
                        f"{SENTINEL}; not retrained (AGENTS.md rule 2)")
    print(f"  {outdir}: complete adapter with no {SENTINEL}; adopted and marked, "
          "not retrained", flush=True)
    return True


def _mark_saved(outdir, note):
    """Write the sentinel. Non-empty, so [ -f ] and [ -s ] both see it."""
    try:
        with open(f"{outdir}/{SENTINEL}", "w") as fh:
            fh.write(note.rstrip("\n") + "\n")
    except OSError as e:
        # A read-only store is not a reason to retrain an adapter that is demonstrably
        # whole. Say it loudly, because without the sentinel the driver will launch this
        # job again -- and it will adopt again, cheaply, every time.
        print(f"  WARNING: could not write {outdir}/{SENTINEL}: {e}", flush=True)


def _publish(tmpdir, outdir, note):
    """Move a finished save from tmpdir into outdir, then mark it. AGENTS.md rule 10.

    Each file lands with os.replace, which is atomic on one filesystem, so no reader ever
    sees a half-written adapter_model.safetensors -- that is the file the gate and the
    harmful eval load, and a partial one of those is indistinguishable from a backbone that
    learned nothing. The sentinel goes last: a kill anywhere in the loop leaves no SAVE_OK,
    _adapter_ready says no, and the next submission retrains the arm instead of gating a
    half-copied one.
    """
    os.makedirs(outdir, exist_ok=True)
    for name in sorted(os.listdir(tmpdir)):
        src, dst = f"{tmpdir}/{name}", f"{outdir}/{name}"
        if os.path.isdir(src):
            shutil.rmtree(dst, ignore_errors=True)
            shutil.move(src, dst)
        else:
            os.replace(src, dst)
    shutil.rmtree(tmpdir, ignore_errors=True)
    _mark_saved(outdir, note)


def report_targets(model):
    """Which towers the shared name list actually reached on this architecture."""
    hit = {}
    for n, _ in model.named_modules():
        leaf = n.rsplit(".", 1)[-1]
        if leaf not in A.TARGETS:
            continue
        tower = "vision" if re.search(r"vision|visual|image_tower", n) else "language"
        hit.setdefault(tower, {}).setdefault(leaf, 0)
        hit[tower][leaf] += 1
    for tower in sorted(hit):
        parts = " ".join(f"{k}={v}" for k, v in sorted(hit[tower].items()))
        print(f"  LORA_TARGETS {tower}: {parts}", flush=True)
    return hit


def encode(r):
    """-> (processor outputs for the full sequence, token length of the user half)."""
    img = Image.open(r["image"]).convert("RGB")
    full = A.pack(proc, TAG, [A.chat_text(proc, r["user"], True, r["assistant"])],
                  [img], maxlen=MAXLEN)
    user = A.pack(proc, TAG, [A.chat_text(proc, r["user"], True)], [img], maxlen=MAXLEN)
    return full, user["input_ids"].shape[1]


def train(arm):
    outdir = f"{ROOT}/adapter_{arm}"
    if _adapter_ready(outdir):
        print(f"== arm {arm}: adapter already present, skipping", flush=True)
        return outdir
    rows = [json.loads(l) for l in open(AFF if arm == "af" else DBF)]
    print(f"== arm {arm}: {len(rows)} demos, {STEPS} steps", flush=True)
    t0 = time.time()
    model = A.load_model(TAG, bnb)
    model = prepare_model_for_kbit_training(
        model, use_gradient_checkpointing=True,
        gradient_checkpointing_kwargs={"use_reentrant": False})
    model.enable_input_require_grads()
    report_targets(model)
    mods = A.TARGETS
    if SCOPE == "lm":
        # Only the text decoder, for a model whose vision tower shares the same leaf names.
        # Two separate things have to be right here, and D35's first attempt had neither.
        #
        # peft treats target_modules as a regex only when it is a *string*: a list is
        # matched with key.endswith(target), so a list holding a regex matches nothing at
        # all and raises NoMatchingPeftModuleError rather than warning.
        #
        # And the text tower is not always under `language_model.`. On gemma-4-31B
        # report_targets finds 60 decoder blocks that the prefix never reaches, so naming
        # the text tower is the wrong move; excluding the vision towers is the portable
        # one, and it uses the same test report_targets already prints beside it.
        mods = r"^(?!.*(?:vision|visual|image_tower)).*\.(?:%s)$" % "|".join(A.TARGETS)
    print(f"  LORA scope={SCOPE} target_modules={mods!r}", flush=True)
    model = get_peft_model(model, LoraConfig(
        r=16, lora_alpha=32, lora_dropout=0.05,
        target_modules=mods, task_type="CAUSAL_LM"))
    model.print_trainable_parameters()

    # prepare_model_for_kbit_training upcasts every non-quantized parameter to fp32, so a
    # norm emits fp32 hidden states into the next 4-bit linear, which wants bf16. Four of
    # the five measured backbones tolerate that; Gemma 4 raises
    #   RuntimeError: expected scalar type BFloat16 but found Float
    # and never completes a step. Casting the non-LoRA floats back to bf16 is the fix. The
    # LoRA parameters stay fp32 on purpose: they are the trainable ones, and peft already
    # casts its adapter input and restores the result dtype around them. Buffers are left
    # alone because rotary inv_freq is fp32 for a reason.
    #
    # Gated on the spec, not applied to everyone: it must not be able to move a number that
    # is already in outputs/report/stats_all_protocols.txt (D29).
    if A.spec(TAG).get("bf16_cast"):
        n_cast = 0
        for n_, p_ in model.named_parameters():
            if p_.dtype == torch.float32 and "lora_" not in n_:
                p_.data = p_.data.to(torch.bfloat16)
                n_cast += 1
        print(f"  bf16_cast: {n_cast} fp32 non-LoRA params back to bfloat16", flush=True)

    # Pre-flight: how many tokens does the loss actually supervise? The v1 run trained on
    # 1-3 word answers (~10 supervised tokens), which collapsed the generator and voided
    # the whole experiment. Refuse to spend GPU time on that again.
    sup, trunc = [], 0
    for r in rows[:30]:
        full, ulen = encode(r)
        total = full["input_ids"].shape[1]
        sup.append(max(total - ulen, 0))
        trunc += int(total >= MAXLEN)
    mean_sup = sum(sup) / max(len(sup), 1)
    # The procedure and the LoRA scope are printed here, in the one line the driver tees back
    # to the local log, because both are env knobs the remote reads and the local side sets.
    # When LORA_SCOPE was read here and forwarded by nobody it crashed three attempts before
    # anyone noticed (D35); a knob whose value never appears in the returned log is a knob
    # that can silently be the default.
    # One line, because the driver tees back only the last PREFLIGHT match (`tail -1`), and a
    # knob whose value never reaches the local log is a knob that can silently be the default
    # -- which is how LORA_SCOPE wasted three attempts before anyone noticed (D35).
    print(f"PREFLIGHT WS={os.environ.get('WS', 'count')} "
          f"supervised tokens/demo: mean={mean_sup:.1f} min={min(sup)} "
          f"max={max(sup)}  truncated={trunc}/{len(sup)} (MAXLEN={MAXLEN})", flush=True)
    if mean_sup < int(os.environ.get("MIN_SUP_TOKENS", "40")):
        print("ABORT: targets too short", flush=True); raise SystemExit(1)
    if trunc:
        print(f"WARNING: {trunc}/{len(sup)} demos hit MAXLEN; target tails are cut",
              flush=True)

    opt = torch.optim.AdamW(model.parameters(), lr=LR, weight_decay=0.01)
    model.train()
    # SEED fixes both the demo order and the LoRA A initialisation, so a seed change moves
    # one thing and not two.
    random.seed(SEED); torch.manual_seed(SEED); torch.cuda.manual_seed_all(SEED)
    print(f"SEED={SEED}", flush=True)
    idxs = list(range(len(rows)))
    tot = 0.0
    for step in range(1, STEPS + 1):
        i = idxs[(step - 1) % len(idxs)]
        if step % len(idxs) == 0:
            random.shuffle(idxs)
        full, ulen = encode(rows[i])
        enc = A.to_device(full, model.device)
        labels = enc["input_ids"].clone()
        labels[0, :ulen] = -100
        out = model(**enc, labels=labels)
        (out.loss / ACCUM).backward()
        tot += out.loss.item()
        if step % ACCUM == 0:
            torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)
            opt.step(); opt.zero_grad()
        if step % 10 == 0:
            print(f"  step {step}/{STEPS}  loss={tot/10:.4f}  ({time.time()-t0:.0f}s)",
                  flush=True)
            tot = 0.0
    # Save beside the target and move it in, never into the target directly. AGENTS.md rule
    # 10, and here it is not a style point: save_pretrained on this partition can be killed
    # mid-write by a REQUEUE preemption, and the truncated adapter_model.safetensors that
    # leaves behind is accepted by every resume guard. The temporary directory is removed
    # first so a previous kill cannot contribute a stale file to this save.
    tmpdir = f"{outdir}.saving"
    shutil.rmtree(tmpdir, ignore_errors=True)
    os.makedirs(tmpdir, exist_ok=True)
    model.save_pretrained(tmpdir)
    _publish(tmpdir, outdir,
             f"arm={arm} tag={TAG} ws={os.environ.get('WS', 'count')} steps={STEPS} "
             f"seed={SEED} scope={SCOPE} secs={time.time()-t0:.0f}")
    print(f"SAVED {outdir} ({time.time()-t0:.0f}s)", flush=True)
    del model
    torch.cuda.empty_cache()
    return outdir


