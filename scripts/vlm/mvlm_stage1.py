# The walltime budget, SECONDS FROM THE START OF THIS PROCESS and not an absolute time: the
# same contract mvlm_gen.py:115 and mvlm_sanity.py:117 already read, so scripts/slurm/
# run_cell.sh can hand phase A the one shared deadline it hands every other phase, with the
# same `TIME_BUDGET="$(budget)"` it passes at run_cell.sh:558, 583 and 648 -- budget() is
# `DEADLINE - now`, seconds remaining, which is what this wants. Handing over DEADLINE
# itself would read as a budget of fifty-odd years and the guard would never fire.
# 0 is the default and means no limit, so every measured Colab run is unchanged.
#
# T_START is taken below, BEFORE the demo build, so a cold build that streams 300 images
# comes out of the budget. That is deliberate: the question the guard answers is whether
# this process can still finish an arm, and the build is time this process has spent.
#
# What it must NOT do is stop an arm part-way, and that is the whole reason it is read here
# rather than inside the step loop. The other two scripts stop at a ROW boundary and the next
# submission resumes from the rows on disk. Training has no such boundary: a LoRA stopped at
# step 90 of 150 is not 60% of an adapter, it is a different adapter, and writing it out is
# precisely the truncated arm the sentinel below exists to keep off the disk. So the budget
# is consulted only BEFORE an arm begins -- either there is room for a whole one or that arm
# is not started at all and the next submission runs it from the first step.
def _budget_seconds():
    """TIME_BUDGET as a float. Unset, empty or malformed all mean no deadline.

    Every valid value parses exactly as mvlm_gen.py:115 and mvlm_sanity.py:117 parse it, so
    the three scripts share one contract. The difference is the EMPTY and the malformed
    value, which a bare float() turns into a ValueError at import -- before the demo build,
    before the first step, in a traceback that names float and not the variable. That is a
    plausible thing to be handed, because the driver builds the value with a shell
    arithmetic expansion, and here it would cost the whole phase rather than a few rows.
    Falling back on the documented default is the safe direction, and it is said out loud,
    because a budget silently read as "no limit" is how this guard sat dead in the first
    place. Unset is silent: that is the Colab default and every measured run took it.
    """
    raw = os.environ.get("TIME_BUDGET")
    if raw is None:
        return 0.0
    try:
        return float(raw.strip())
    except ValueError:
        print(f"WARNING: TIME_BUDGET={raw!r} is not a number, so this run has NO deadline "
              "and the ARM_SECONDS guard cannot fire. Whatever was meant to pass seconds "
              "remaining passed something else; fix it there.", flush=True)
        return 0.0


