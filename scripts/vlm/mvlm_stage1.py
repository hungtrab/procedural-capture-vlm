"""Build the benign demos and train both adapters for one vision model.

The twin of txt_stage1.py, for vision backbones other than the Llama-3.2-11B-Vision anchor.
Two arms are trained from the same 300 image descriptions:

  af  the worksheet procedure, with the answer first and then the word count
  db  the identical description with no procedure around it

Both arms see the same images, the same descriptions and the same number of supervised
tokens, so a difference between them afterwards cannot come from content or from length.

The demos are rebuilt here rather than uploaded. LLaVA-ReCap-CC3M is streamed in order and
filtered by one rule (answer of at least MIN_WORDS words), so every model gets the same 300
demos without 300 images crossing the wire once per model. The build is deterministic; the
printed median word count is the check that it really was the same set.

Writes /content/mvlm/<tag>/adapter_{af,db}/ plus 30MB split parts under .../aparts/, which
the driver downloads so no later VM has to retrain. Retraining per VM would mean rows
generated by adapters that are only nominally the same.

Env: TAG (model tag from mvlm_arch), N_TRAIN, MIN_WORDS, STEPS, LR, ACCUM, MAXLEN, SEED,
     ARMS, LORA_SCOPE (all|lm).
"""
import os, sys, subprocess, json, time, hashlib, glob, re, shutil

sys.path.insert(0, "/content")
import mvlm_arch as _A  # module-level imports: os only, so this is safe before pip runs
_TF = _A.tf_pin(os.environ["TAG"])

subprocess.run([sys.executable, "-m", "pip", "install", "-q", "-U",
                _TF, "peft", "accelerate", "bitsandbytes",
                "datasets"], check=False)
subprocess.run([sys.executable, "-m", "pip", "install", "-q", "pillow==10.4.0"], check=False)
os.environ["HF_TOKEN"] = open("/content/hf_token.txt").read().strip()

import torch, random
from transformers import BitsAndBytesConfig
from peft import LoraConfig, get_peft_model, prepare_model_for_kbit_training
from PIL import Image
import mvlm_arch as A
import mvlm_data as D

TAG = os.environ["TAG"]
SP_ = A.spec(TAG)
ROOT = f"/content/mvlm/{TAG}"
DATA = "/content/mvlm/data"              # shared across tags on the same VM
N_TRAIN = int(os.environ.get("N_TRAIN", "300"))
MIN_WORDS = int(os.environ.get("MIN_WORDS", "60"))
STEPS = int(os.environ.get("STEPS", "150"))
LR = float(os.environ.get("LR", "1e-4"))
ACCUM = int(os.environ.get("ACCUM", "8"))
MAXLEN = int(os.environ.get("MAXLEN", "1536"))
SEED = int(os.environ.get("SEED", "42"))
SCOPE = os.environ.get("LORA_SCOPE", "all")
ARMS = [a.strip() for a in os.environ.get("ARMS", "af,db").split(",") if a.strip()]
os.makedirs(ROOT, exist_ok=True)
os.makedirs(DATA + "/train_imgs", exist_ok=True)
print(f"TAG={TAG} model={SP_['mid']} ({SP_['params']}) scope={SCOPE}", flush=True)

# The demo build lives in mvlm_data so the sanity gate builds the same rows from the same
# code. For the first N_TRAIN items the question pool rotates on the train counter alone, so
# the demos are bit-identical to what the earlier models in this run already trained on.
P = D.build(DATA, N_TRAIN, int(os.environ.get("N_HOLDOUT", "40")), MIN_WORDS)
AFF, DBF = P["train_af"], P["train_db"]
for nm in ("train_af", "train_db"):
    r = json.loads(open(P[nm]).readline())
    print(f"\n[{nm}] USER: {r['user'][:240]}", flush=True)
    print(f"[{nm}] ASSISTANT: {r['assistant'][:240]}", flush=True)

# ---------- train ----------
bnb = BitsAndBytesConfig(load_in_4bit=True, bnb_4bit_quant_type="nf4",
                         bnb_4bit_compute_dtype=torch.bfloat16,
                         bnb_4bit_use_double_quant=True)
proc = A.load_proc(TAG)


def split_parts(path, outdir, name, chunk=30 << 20):
    os.makedirs(outdir, exist_ok=True)
    for old in glob.glob(f"{outdir}/{name}.p*"):
        os.remove(old)
    with open(path, "rb") as fh:
        i = 0
        while True:
            b = fh.read(chunk)
            if not b:
                break
            open(f"{outdir}/{name}.p{i:02d}", "wb").write(b)
            i += 1
    h = hashlib.md5(open(path, "rb").read()).hexdigest()
    print(f"  {name}: {i} parts, md5={h}", flush=True)


def report_targets(model):
    """Which towers the shared name list actually reached on this architecture."""
    hit = {}
    for n, _ in model.named_modules():
        leaf = n.rsplit(".", 1)[-1]
        if leaf not in A.TARGETS:
            continue
        tower = "vision" if re.search(r"vision|visual|image_tower", n) else "language"
        hit.setdefault(tower, {}).setdefault(leaf, 0)
        hit[tower][leaf] += 1
    for tower in sorted(hit):
        parts = " ".join(f"{k}={v}" for k, v in sorted(hit[tower].items()))
        print(f"  LORA_TARGETS {tower}: {parts}", flush=True)
    return hit


def encode(r):
    """-> (processor outputs for the full sequence, token length of the user half)."""
    img = Image.open(r["image"]).convert("RGB")
    full = A.pack(proc, TAG, [A.chat_text(proc, r["user"], True, r["assistant"])],
                  [img], maxlen=MAXLEN)
    user = A.pack(proc, TAG, [A.chat_text(proc, r["user"], True)], [img], maxlen=MAXLEN)
    return full, user["input_ids"].shape[1]


def train(arm):
    outdir = f"{ROOT}/adapter_{arm}"
    if os.path.exists(f"{outdir}/adapter_model.safetensors"):
        print(f"== arm {arm}: adapter already present, skipping", flush=True)
        return outdir
    rows = [json.loads(l) for l in open(AFF if arm == "af" else DBF)]
    print(f"== arm {arm}: {len(rows)} demos, {STEPS} steps", flush=True)
    t0 = time.time()
    model = A.load_model(TAG, bnb)
    model = prepare_model_for_kbit_training(
        model, use_gradient_checkpointing=True,
        gradient_checkpointing_kwargs={"use_reentrant": False})
    model.enable_input_require_grads()
    report_targets(model)
    mods = A.TARGETS
    if SCOPE == "lm":
        # Only the text decoder, for a model whose vision tower shares the same leaf names.
        # Two separate things have to be right here, and D35's first attempt had neither.
        #
        # peft treats target_modules as a regex only when it is a *string*: a list is
        # matched with key.endswith(target), so a list holding a regex matches nothing at
        # all and raises NoMatchingPeftModuleError rather than warning.
        #
        # And the text tower is not always under `language_model.`. On gemma-4-31B
        # report_targets finds 60 decoder blocks that the prefix never reaches, so naming
        # the text tower is the wrong move; excluding the vision towers is the portable
        # one, and it uses the same test report_targets already prints beside it.
        mods = r"^(?!.*(?:vision|visual|image_tower)).*\.(?:%s)$" % "|".join(A.TARGETS)
    print(f"  LORA scope={SCOPE} target_modules={mods!r}", flush=True)
    model = get_peft_model(model, LoraConfig(
        r=16, lora_alpha=32, lora_dropout=0.05,
        target_modules=mods, task_type="CAUSAL_LM"))
    model.print_trainable_parameters()

    # prepare_model_for_kbit_training upcasts every non-quantized parameter to fp32, so a
    # norm emits fp32 hidden states into the next 4-bit linear, which wants bf16. Four of
    # the five measured backbones tolerate that; Gemma 4 raises
    #   RuntimeError: expected scalar type BFloat16 but found Float
    # and never completes a step. Casting the non-LoRA floats back to bf16 is the fix. The
    # LoRA parameters stay fp32 on purpose: they are the trainable ones, and peft already
    # casts its adapter input and restores the result dtype around them. Buffers are left
    # alone because rotary inv_freq is fp32 for a reason.
    #
    # Gated on the spec, not applied to everyone: it must not be able to move a number that
    # is already in outputs/report/stats_all_protocols.txt (D29).
    if A.spec(TAG).get("bf16_cast"):
        n_cast = 0
        for n_, p_ in model.named_parameters():
            if p_.dtype == torch.float32 and "lora_" not in n_:
                p_.data = p_.data.to(torch.bfloat16)
                n_cast += 1
        print(f"  bf16_cast: {n_cast} fp32 non-LoRA params back to bfloat16", flush=True)

    # Pre-flight: how many tokens does the loss actually supervise? The v1 run trained on
    # 1-3 word answers (~10 supervised tokens), which collapsed the generator and voided
    # the whole experiment. Refuse to spend GPU time on that again.
    sup, trunc = [], 0
    for r in rows[:30]:
        full, ulen = encode(r)
        total = full["input_ids"].shape[1]
        sup.append(max(total - ulen, 0))
        trunc += int(total >= MAXLEN)
    mean_sup = sum(sup) / max(len(sup), 1)
    # The procedure and the LoRA scope are printed here, in the one line the driver tees back
    # to the local log, because both are env knobs the remote reads and the local side sets.
    # When LORA_SCOPE was read here and forwarded by nobody it crashed three attempts before
    # anyone noticed (D35); a knob whose value never appears in the returned log is a knob
    # that can silently be the default.
    # One line, because the driver tees back only the last PREFLIGHT match (`tail -1`), and a
    # knob whose value never reaches the local log is a knob that can silently be the default
    # -- which is how LORA_SCOPE wasted three attempts before anyone noticed (D35).
    print(f"PREFLIGHT WS={os.environ.get('WS', 'count')} "
          f"supervised tokens/demo: mean={mean_sup:.1f} min={min(sup)} "
          f"max={max(sup)}  truncated={trunc}/{len(sup)} (MAXLEN={MAXLEN})", flush=True)
    if mean_sup < int(os.environ.get("MIN_SUP_TOKENS", "40")):
        print("ABORT: targets too short", flush=True); raise SystemExit(1)
    if trunc:
        print(f"WARNING: {trunc}/{len(sup)} demos hit MAXLEN; target tails are cut",
              flush=True)

    opt = torch.optim.AdamW(model.parameters(), lr=LR, weight_decay=0.01)
    model.train()
    # SEED fixes both the demo order and the LoRA A initialisation, so a seed change moves
    # one thing and not two.
    random.seed(SEED); torch.manual_seed(SEED); torch.cuda.manual_seed_all(SEED)
    print(f"SEED={SEED}", flush=True)
    idxs = list(range(len(rows)))
    tot = 0.0
    for step in range(1, STEPS + 1):
        i = idxs[(step - 1) % len(idxs)]
        if step % len(idxs) == 0:
            random.shuffle(idxs)
        full, ulen = encode(rows[i])
        enc = A.to_device(full, model.device)
        labels = enc["input_ids"].clone()
        labels[0, :ulen] = -100
        out = model(**enc, labels=labels)
        (out.loss / ACCUM).backward()
        tot += out.loss.item()
        if step % ACCUM == 0:
            torch.nn.utils.clip_grad_norm_(model.parameters(), 1.0)
            opt.step(); opt.zero_grad()
        if step % 10 == 0:
            print(f"  step {step}/{STEPS}  loss={tot/10:.4f}  ({time.time()-t0:.0f}s)",
                  flush=True)
            tot = 0.0
    os.makedirs(outdir, exist_ok=True)
    model.save_pretrained(outdir)
    print(f"SAVED {outdir} ({time.time()-t0:.0f}s)", flush=True)
    del model
    torch.cuda.empty_cache()
    return outdir


for arm in ARMS:
    d = train(arm)
    split_parts(f"{d}/adapter_model.safetensors", ROOT + "/aparts", f"adapter_{arm}")
    shutil.copy(f"{d}/adapter_config.json", f"{ROOT}/aparts/adapter_{arm}.config.json")
print("MVLM_STAGE1_DONE", flush=True)
