#!/usr/bin/env bash
# Procedural capture across vision backbones, end to end, one model tag at a time.
#
# The anchor result is Llama-3.2-11B-Vision. This runs the identical protocol on five more
# vision models spanning roughly 4B to 33B, two families scaled inside themselves
# (Qwen2.5-VL 3B/7B/32B, Gemma-3 4B/12B), so size can be read apart from family. Nothing
# about the experiment moves except the backbone: same 300 LLaVA-ReCap-CC3M demos, same
# worksheet, same 260 AdvBench items on the same gray square, same LoRA settings, same
# seed, same two guards, both judging protocols.
#
# Per tag, two phases, because training is short and generation is long:
#   A. one VM trains af and db and the driver pulls the adapters down in 30MB parts, so no
#      later VM retrains. Retraining per VM would mean rows generated by adapters that are
#      only nominally identical.
#   B. rounds of detached-and-polled generation, then both guards, then the request-free
#      protocol.
# Phase A is skipped once the adapters are on disk and phase B resumes from the row count,
# so the whole thing is restartable at any point.
#
# Conditions are named gray_<tag>, which is not cosmetic: check_engagement.py reads the step
# marker off the leading condition name and run_neutral_judge.sh picks the request-free
# prompt off the _gray prefix, so the existing analysis scripts need no change.
#
# Env: TAGS, ARMS, ROUNDS, BS (per-tag default below), BUDGET, STEPS, SEED, N_TRAIN,
#      SKIP_JUDGE, ONLY_PHASE (a|b|judge), A_GROUPS.
#
# A_GROUPS controls how phase A is split across VMs: a space separated list of comma
# separated arm groups, one fresh VM per group. The default "af,db" trains both arms on one
# VM, which is what every backbone up to 12B was measured with. At 33B that does not fit: a
# Colab GPU VM is reclaimed at 21-23 minutes (see the colab memory note), and training two
# 33B arms took 17.5 minutes, so the 566MB adapter transfer ran past the reclaim and the DB
# adapter came back as a zero byte file (md5 d41d8cd98f00...). Both arms had trained fine.
# A_GROUPS="af db" gives each arm its own VM and its own transfer window, which is D14
# applied to a model that outgrew the one-VM budget.
set -u
cd "$(dirname "$0")/../.."
SP="${SP:?scratchpad path required}"
TAGS="${TAGS:-q3,g4,q7,g12,q32}"
ARMS="${ARMS:-base,af,db}"
ROUNDS="${ROUNDS:-10}"; BUDGET="${BUDGET:-1200}"
STEPS="${STEPS:-150}"; SEED="${SEED:-42}"; N_TRAIN="${N_TRAIN:-300}"
ONLY_PHASE="${ONLY_PHASE:-}"
A_GROUPS="${A_GROUPS:-af,db}"
# SUF keeps a smoke run (SUF=_smoke) or a seed replication (SUF=_s1) off the
# real adapters and the real result directory
SUF="${SUF:-}"
# ASUF is the adapter-store suffix, normally the same as SUF. They are separable for one
# reason: the NOIMG lesion is a new *condition* on adapters that already exist, so it wants
# SUF=_noimg for its own output directory while still reading adapters_store/mvlm_<tag>.
# Passing SUF alone would send the driver looking for adapters that were never trained.
ASUF="${ASUF-$SUF}"
# NOIMG=1 removes the image from the prompt, placeholder and pixels both; see mvlm_gen.py.
# The prompt text is left byte-identical, still saying "about the image", so the single
# variable under test is the presence of the visual input and not a rewording.
NOIMG="${NOIMG:-}"
# all|lm. mvlm_stage1.py reads it but nothing forwarded it to the remote, so D35's
# prescribed fix for gemma-4-31B silently ran with the default and kept crashing.
LORA_SCOPE="${LORA_SCOPE:-all}"
# WS picks the procedure the demos teach: count (published) or chain (D42). It has to
# reach the training VM, because mvlm_data builds the demos there; a WS set only here
# would train the published worksheet and evaluate the chained one.
WS="${WS:-count}"
EVAL_LOCAL="${EVAL_LOCAL:-$SP/data/eval_harmful_gray.jsonl}"
mkdir -p "$SP/log"
LOG="$SP/log/mvlm.log"
say(){ echo "[mvlm] $(date +%H:%M:%S) $*" | tee -a "$LOG"; }
rows(){ [ -f "$1" ] && wc -l < "$1" || echo 0; }

[ -s "$EVAL_LOCAL" ] || { say "missing eval set $EVAL_LOCAL"; exit 1; }
N_EVAL=$(wc -l < "$EVAL_LOCAL")
say "eval set: $N_EVAL rows; tags=$TAGS"

# A blind download can catch a half-written final line; drop it so the file stays valid.
trim(){ python3 - "$1" <<'PY'
import sys, json, os
p = sys.argv[1]
if not os.path.exists(p): raise SystemExit
good = []
for line in open(p, errors="replace"):
    try: json.loads(line)
    except Exception: continue
    good.append(line if line.endswith("\n") else line + "\n")
open(p, "w").writelines(good)
PY
}

# The accelerators to try, in order, pipe-separated. The default is the pair every row in
# outputs/report/stats_all_protocols.txt was produced on, so an existing command line is
# unchanged. It is an env var because the small backbones do not need an A100 -- q3 is 3.8B
# in 4-bit -- and AGENTS.md forbids mixing hardware inside one experiment, not across
# experiments: a GPUS=--gpu L4 run must have ALL its own cells on L4 and must not be pooled
# with, or differenced against, an A100 row.
GPUS="${GPUS:---gpu A100 --high-mem|--gpu A100}"

newvm(){ # $1 = session name
  local made=0 hw
  local -a HWS
  # Split GPUS on '|' into an array, and do it with `IFS='|' read` rather than by setting
  # IFS for the whole loop. Setting it for the loop is what broke the first L4 run: with
  # IFS='|' in force, `colab new $hw` no longer word-splits "--gpu L4" on the space, so the
  # CLI received one argument "--gpu L4" and answered "No such option: --gpu L4". Every
  # accelerator in the list failed that way and the run reported "no VM" as if none were
  # free. `IFS='|' read` applies the change to the read alone, so $hw splits normally here.
  IFS='|' read -r -a HWS <<< "$GPUS"
  for hw in "${HWS[@]}"; do
    if timeout 600 colab new $hw -s "$1" < /dev/null >>"$LOG" 2>&1; then
      say "  got $hw"; made=1; break
    fi
    say "  unavailable: $hw"
  done
  [ "$made" = 1 ]
}

push(){ timeout 600 colab upload -s "$S" "$1" "$2" < /dev/null >>"$LOG" 2>&1 \
          || say "UPLOAD FAILED $1"; }

# Batch size per tag. The large models get a smaller batch because the KV cache for eight
# sequences of ~700 tokens plus a 4-bit 33B backbone is what would push an A100 over.
bs_for(){ case "$1" in q32) echo 4 ;; g12|gm412) echo 6 ;; *) echo 8 ;; esac; }

# Uploading into a directory that does not exist yet fails almost silently (the contents
# API 404s), which is what made an early run upload nothing at all.
mkdirs(){ cat > "$SP/stage_mvlmdirs.py" <<PY
import os
for d in ("/content/mvlm", "/content/mvlm/data", "/content/mvlm/data/train_imgs",
          "/content/mvlm/$1", "/content/mvlm/$1/adapter_af",
          "/content/mvlm/$1/adapter_db", "/content/mvlm/$1/aparts",
          "/content/mvlm/$1/aparts_up"):
    os.makedirs(d, exist_ok=True)
print("DIRS_OK", flush=True)
PY
  timeout 200 colab exec -s "$S" --timeout 120 -f "$SP/stage_mvlmdirs.py" \
    < /dev/null 2>&1 | grep -E "DIRS_OK|Error" | tee -a "$LOG" || true
}

for tag in ${TAGS//,/ }; do
  ADIR="adapters_store/mvlm_${tag}${ASUF}"
  COND="gray_${tag}${SUF}"
  OUTDIR="outputs/vlm2_$COND"
  BSX="${BS:-$(bs_for "$tag")}"
  mkdir -p "$ADIR" "$OUTDIR"
  say "########## $tag (cond $COND, BS=$BSX) ##########"

  have_adapters(){
    for a in ${ARMS//,/ }; do
      [ "$a" = base ] && continue
      [ -s "$ADIR/adapter_$a/adapter_model.safetensors" ] || return 1
    done
    return 0
  }
  # the arms of ONE phase A group; have_adapters spans every arm the run needs
  have_group(){
    for a in ${1//,/ }; do
      [ -s "$ADIR/adapter_$a/adapter_model.safetensors" ] || return 1
    done
    return 0
  }

  # ---------------- phase A: train ----------------
  if [ "$ONLY_PHASE" = b ] || [ "$ONLY_PHASE" = judge ]; then
    :
  elif have_adapters; then
    say "$tag: adapters already on disk, skipping training"
  else
    # Three attempts with a fresh VM each. Everything here is defensive for a reason found
    # the hard way: a run once read a STALE remote log, saw the done marker in it, and spent
    # twenty minutes retrying the download of adapters that had never been trained, because
    # the launch exec had died with "Connection was lost." and nothing was running at all.
    gi=0
    for group in $A_GROUPS; do
    gi=$(( gi + 1 ))
    for attempt in 1 2 3; do
      have_group "$group" && break
      RLOG="$SP/log/mvlm1_${tag}.log"
      rm -f "$RLOG"                 # never let a previous run's log look like progress
      S="mv${tag}t${gi}$attempt"
      say "=== $tag phase A group $group attempt $attempt (STEPS=$STEPS SEED=$SEED) ==="
      newvm "$S" || { say "  no VM; next attempt"; continue; }
      push .hf /content/hf_token.txt
      push scripts/vlm/mvlm_arch.py /content/mvlm_arch.py
      push scripts/vlm/mvlm_data.py /content/mvlm_data.py
      push scripts/vlm/mvlm_items.py /content/mvlm_items.py
      push scripts/vlm/mvlm_stage1.py /content/mvlm_stage1.py
      push scripts/vlm/launch_bg.py /content/launch_bg.py
      mkdirs "$tag"
      cat > "$SP/stage_mvlmtrain.py" <<PY
import os, subprocess, sys
os.environ.update({"BG_SCRIPT": "/content/mvlm_stage1.py",
                   "BG_LOG": "/content/mvlm1.log",
                   "TAG": "${tag}", "STEPS": "${STEPS}", "SEED": "${SEED}",
                   "ARMS": "${group}", "N_TRAIN": "${N_TRAIN}",
                   "LORA_SCOPE": "${LORA_SCOPE}", "WS": "${WS}"})
r = subprocess.run([sys.executable, "/content/launch_bg.py"], capture_output=True, text=True)
print(r.stdout, r.stderr[-800:], flush=True)
PY
      # the launch exec itself is the flaky step, so retry it on the same VM first
      launched=0
      for try in 1 2 3; do
        timeout 300 colab exec -s "$S" --timeout 180 -f "$SP/stage_mvlmtrain.py" \
          < /dev/null > "$SP/mvlmtrain_exec.txt" 2>&1
        if grep -q LAUNCHED "$SP/mvlmtrain_exec.txt"; then launched=1; break; fi
        say "  launch attempt $try failed: $(grep -oE 'RuntimeError.*' "$SP/mvlmtrain_exec.txt" | head -1)"
        sleep 15
      done
      if [ "$launched" = 0 ]; then
        say "  could not launch training; next attempt"
        timeout 120 colab stop -s "$S" < /dev/null >>"$LOG" 2>&1
        continue
      fi
      say "  launched; polling for adapters"
      done_seen=0
      for poll in $(seq 1 40); do
        sleep 45
        timeout 120 colab download -s "$S" /content/mvlm1.log "$RLOG" \
          < /dev/null >/dev/null 2>&1
        grep -E "ABORT|Traceback|OutOfMemory|Error" "$RLOG" 2>/dev/null | tail -2 | tee -a "$LOG"
        grep -E "^  step |SAVED|parts, md5|LORA_TARGETS|trainable|PREFLIGHT|benign target" \
          "$RLOG" 2>/dev/null | tail -1 | tee -a "$LOG"
        if ! grep -q "MVLM_STAGE1_DONE" "$RLOG" 2>/dev/null; then continue; fi
        done_seen=$(( done_seen + 1 ))
        for a in ${group//,/ }; do   # only the arms this VM was asked to train
          [ -s "$ADIR/adapter_$a/adapter_model.safetensors" ] && continue
          mkdir -p "$ADIR/adapter_$a"
          timeout 120 colab download -s "$S" \
            "/content/mvlm/$tag/aparts/adapter_$a.config.json" \
            "$ADIR/adapter_$a/adapter_config.json" < /dev/null >/dev/null 2>&1 || continue
          : > "$SP/ap_$a.bin"; ok=1
          # a 33B adapter is ~19 parts, so the ceiling here is well above any model in the set
          for i in $(seq -w 0 39); do
            if timeout 300 colab download -s "$S" \
                 "/content/mvlm/$tag/aparts/adapter_$a.p$i" \
                 "$SP/ap_${a}_$i" < /dev/null >/dev/null 2>&1; then
              cat "$SP/ap_${a}_$i" >> "$SP/ap_$a.bin"; rm -f "$SP/ap_${a}_$i"
            else
              [ "$i" = 00 ] && ok=0
              break
            fi
          done
          # The remote printed the md5 of the file it saved. Checking the reassembled
          # download against THAT is the only way a truncated transfer cannot pass:
          # comparing a local file with its own md5 proves nothing.
          want=$(grep -oE "adapter_$a: [0-9]+ parts, md5=[0-9a-f]+" "$RLOG" | tail -1 \
                   | sed "s/.*md5=//")
          got=$(md5sum "$SP/ap_$a.bin" 2>/dev/null | cut -d" " -f1)
          if [ "$ok" = 1 ] && [ -n "$want" ] && [ "$got" = "$want" ]; then
            mv "$SP/ap_$a.bin" "$ADIR/adapter_$a/adapter_model.safetensors"
            say "  adapter $a OK ($(stat -c%s "$ADIR/adapter_$a/adapter_model.safetensors") bytes, md5 ${want:0:12})"
          else
            rm -f "$SP/ap_$a.bin"
            say "  adapter $a transfer bad (want ${want:0:12} got ${got:0:12}); will retry"
          fi
        done
        have_group "$group" && { say "  group $group downloaded"; break; }
        [ "$done_seen" -ge 6 ] && { say "  training done but adapters will not transfer"; break; }
      done
      timeout 120 colab stop -s "$S" < /dev/null >>"$LOG" 2>&1
    done
    done
    have_adapters || { say "$tag: PHASE A FAILED -- no adapters, skipping this model"; continue; }
  fi

  if [ "$ONLY_PHASE" = a ]; then say "$tag: phase A only, stopping here"; continue; fi
  have_adapters || { say "$tag: no adapters on disk, cannot generate"; continue; }
  MD5_AF=$(md5sum "$ADIR/adapter_af/adapter_model.safetensors" | cut -d" " -f1)
  MD5_DB=$(md5sum "$ADIR/adapter_db/adapter_model.safetensors" | cut -d" " -f1)
  say "$tag adapters: af=${MD5_AF:0:12} db=${MD5_DB:0:12}"

  # ---------------- phase B: generate ----------------
  complete(){ for a in ${ARMS//,/ }; do
      [ "$(rows "$OUTDIR/res_${a}.jsonl")" -ge "$N_EVAL" ] || return 1; done; return 0; }

  if [ "$ONLY_PHASE" != judge ]; then
  crashes=0
  for round in $(seq 1 "$ROUNDS"); do
    if complete; then say "$tag: all arms at $N_EVAL rows"; break; fi
    S="mv${tag}g$round"
    tot=0; for a in ${ARMS//,/ }; do tot=$(( tot + $(rows "$OUTDIR/res_${a}.jsonl") )); done
    say "=== $tag phase B round $round (have $tot/$(( N_EVAL * 3 )) rows) ==="
    newvm "$S" || { sleep 60; continue; }
    push .hf /content/hf_token.txt
    push scripts/vlm/mvlm_arch.py /content/mvlm_arch.py
    push scripts/vlm/mvlm_gen.py /content/mvlm_gen.py
    push scripts/vlm/launch_bg.py /content/launch_bg.py
    mkdirs "$tag"
    push "$EVAL_LOCAL" "/content/mvlm/$tag/eval_harmful_gray.jsonl"
    # ~160MB to ~570MB per adapter in 30MB parts, five at a time with one retry each: a
    # single transient failure here used to cost a whole round. Parts are built and removed
    # one arm at a time, so the driver never holds two full copies on disk.
    : > "$SP/upfail_mvlm"
    for a in af db; do
      push "$ADIR/adapter_$a/adapter_config.json" \
           "/content/mvlm/$tag/adapter_$a/adapter_config.json"
      rm -f "$SP"/up_${a}_*
      split -b 30m -d -a 2 "$ADIR/adapter_$a/adapter_model.safetensors" "$SP/up_${a}_"
      for p in "$SP"/up_${a}_*; do
        ( timeout 600 colab upload -s "$S" "$p" \
            "/content/mvlm/$tag/aparts_up/$(basename "$p")" < /dev/null >/dev/null 2>&1 \
          || timeout 600 colab upload -s "$S" "$p" \
               "/content/mvlm/$tag/aparts_up/$(basename "$p")" < /dev/null >/dev/null 2>&1 \
          || echo "$(basename "$p")" >> "$SP/upfail_mvlm" ) &
        while [ "$(jobs -rp | wc -l)" -ge 5 ]; do sleep 1; done
      done
      wait
      rm -f "$SP"/up_${a}_*
    done
    if [ -s "$SP/upfail_mvlm" ]; then
      say "  PART UPLOADS FAILED: $(tr '\n' ' ' < "$SP/upfail_mvlm")"
    fi
    for a in ${ARMS//,/ }; do
      f="$OUTDIR/res_${a}.jsonl"
      [ -f "$f" ] && push "$f" "/content/mvlm/$tag/res_${a}.jsonl"
    done
    cat > "$SP/stage_mvlmgen.py" <<PY
import os, glob, hashlib, subprocess, sys
root = "/content/mvlm/${tag}"
for a in ("af", "db"):
    parts = sorted(glob.glob(root + "/aparts_up/up_%s_*" % a))
    if parts:
        with open(root + "/adapter_%s/adapter_model.safetensors" % a, "wb") as fh:
            for p in parts:
                fh.write(open(p, "rb").read())
exp = {"af": "${MD5_AF}", "db": "${MD5_DB}"}
for a in ("af", "db"):
    f = root + "/adapter_%s/adapter_model.safetensors" % a
    h = hashlib.md5(open(f, "rb").read()).hexdigest()
    print(a, "md5", h, os.path.getsize(f), flush=True)
    if h != exp[a]:
        print("MISMATCH", a, flush=True); sys.exit(1)
print("ADAPTERS_OK", flush=True)
os.environ.update({"BG_SCRIPT": "/content/mvlm_gen.py", "BG_LOG": "/content/mvlmgen.log",
                   "TAG": "${tag}", "ARMS": "${ARMS}", "BS": "${BSX}",
                   "TIME_BUDGET": "${BUDGET}",
                   "EVALF": root + "/eval_harmful_gray.jsonl", "SFX": "",
                   "NOIMG": "${NOIMG}"})
r = subprocess.run([sys.executable, "/content/launch_bg.py"], capture_output=True, text=True)
print(r.stdout, r.stderr[-800:], flush=True)
PY
    timeout 600 colab exec -s "$S" --timeout 500 -f "$SP/stage_mvlmgen.py" \
      < /dev/null > "$SP/mvlmgen_exec.txt" 2>&1
    grep -E "ADAPTERS_OK|MISMATCH|LAUNCHED|md5|Error" "$SP/mvlmgen_exec.txt" \
      | tee -a "$LOG" || true
    if ! grep -q LAUNCHED "$SP/mvlmgen_exec.txt"; then
      say "  launch failed (adapters not assembled?); next round"
      timeout 120 colab stop -s "$S" < /dev/null >>"$LOG" 2>&1
      continue
    fi
    # same stale-log hazard as phase A: a done marker left here by an earlier round would
    # end the poll before the new job had written a single row
    rm -f "$SP/log/mvlmgen_${tag}.log"
    say "  polling every 30s"
    stall=0
    while true; do
      sleep 30
      got=0
      for a in ${ARMS//,/ }; do
        timeout 120 colab download -s "$S" "/content/mvlm/$tag/res_${a}.jsonl" \
          "$OUTDIR/res_${a}.jsonl" < /dev/null >/dev/null 2>&1 && got=1
        trim "$OUTDIR/res_${a}.jsonl"
      done
      timeout 120 colab download -s "$S" /content/mvlmgen.log \
        "$SP/log/mvlmgen_${tag}.log" < /dev/null >/dev/null 2>&1
      # The remote job has no try/except, so a traceback in its log means it is dead and no
      # further row will ever arrive. Without this the driver polls a corpse for the rest of
      # the VM's life, which is exactly what the Gemma image-nesting bug cost twice.
      if grep -q "^Traceback" "$SP/log/mvlmgen_${tag}.log" 2>/dev/null; then
        say "  remote job crashed:"
        grep -E "Error|error:" "$SP/log/mvlmgen_${tag}.log" | tail -3 | tee -a "$LOG"
        crashes=$(( crashes + 1 ))
        break
      fi
      tot=0; for a in ${ARMS//,/ }; do tot=$(( tot + $(rows "$OUTDIR/res_${a}.jsonl") )); done
      say "  polled: total $tot rows$( [ "$got" = 0 ] && echo ' (nothing yet)')"
      if complete; then say "  all arms complete"; break; fi
      if [ "$got" = 0 ]; then stall=$(( stall + 1 )); else stall=0; fi
      [ "$stall" -ge 8 ] && { say "  session unreachable; next round"; break; }
      if grep -q "MVLM_MULTI_" "$SP/log/mvlmgen_${tag}.log" 2>/dev/null; then
        say "  remote job finished"; break
      fi
    done
    timeout 120 colab stop -s "$S" < /dev/null >>"$LOG" 2>&1
    # a bug reproduces on every VM, so stop paying for it after the second identical crash
    [ "$crashes" -ge 2 ] && { say "$tag: crashed twice, giving up on this model"; break; }
  done
  fi

  say "$tag FINAL:"
  for a in ${ARMS//,/ }; do say "  $a: $(rows "$OUTDIR/res_${a}.jsonl")/$N_EVAL"; done

  # ---------------- judges ----------------
  if [ -n "${SKIP_JUDGE:-}" ]; then say "$tag: judging skipped"; continue; fi
  if ! complete; then say "$tag: incomplete, not judging"; continue; fi
  for J in lg qg; do
    say "=== $tag: judge $J (raw protocol) ==="
    SP="$SP" SFX="_$COND" ARMS="$ARMS" JUDGE="$J" ROUNDS=8 BS=12 \
      bash scripts/vlm/run_v3_judge.sh 2>&1 | sed "s/^/[mvlm] /"
  done
  say "=== $tag: request-free protocol ==="
  SP="$SP" SFX="_$COND" ARMS="$ARMS" bash scripts/vlm/run_neutral_judge.sh 2>&1 \
    | sed "s/^/[mvlm] /"
  say "$tag DONE"
done
say "RUN_MVLM_DONE"
