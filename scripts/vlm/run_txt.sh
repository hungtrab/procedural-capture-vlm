#!/usr/bin/env bash
# Text-only control, end to end: train both adapters on Llama-3.1-8B, then run the same
# harmful eval the VLM arms were run on, then judge it with the same two guards.
#
# This is the answer to "why is this a vision paper if the request is in the text channel?".
# `noimg` answers it inside the model (withhold the image); this answers it across models
# (same procedure, same AdvBench prompts, no image anywhere, matched text backbone).
#
# Two phases, because training is short and generation is long:
#   A. one VM trains af and db (~minutes) and the driver downloads the adapters in 30MB
#      parts, so no later VM ever has to retrain -- the adapters are then fixed for every
#      round, which matters: retraining per VM would mean rows generated by adapters that
#      are only nominally identical.
#   B. rounds of generation, detached + polled, exactly like run_v3_gen.sh.
# Phase A is skipped once the adapters are on disk, so the whole thing is resumable.
#
# Env: ARMS, CONDS (txt|txtplain), ROUNDS, BS, BUDGET, STEPS, SEED, SKIP_JUDGE, ADIR,
#      N_TRAIN.
set -u
cd "$(dirname "$0")/../.."
SP="${SP:?scratchpad path required}"
ARMS="${ARMS:-base,af,db}"
CONDS="${CONDS:-txt}"
ROUNDS="${ROUNDS:-10}"; BS="${BS:-8}"; BUDGET="${BUDGET:-1200}"
STEPS="${STEPS:-150}"; SEED="${SEED:-42}"; N_TRAIN="${N_TRAIN:-300}"
# ADIR is overridable so a STEPS=5 smoke run cannot overwrite the real adapters
ADIR="${ADIR:-adapters_store/llama31_txt}"
mkdir -p "$ADIR" "$SP/log"
LOG="$SP/log/txt.log"
say(){ echo "[txt] $(date +%H:%M:%S) $*" | tee -a "$LOG"; }
rows(){ [ -f "$1" ] && wc -l < "$1" || echo 0; }

# A blind download can catch a half-written final line; drop it so the file stays valid.
trim(){ python3 - "$1" <<'PY'
import sys, json, os
p = sys.argv[1]
if not os.path.exists(p): raise SystemExit
good = []
for line in open(p, errors="replace"):
    try: json.loads(line)
    except Exception: continue
    good.append(line if line.endswith("\n") else line + "\n")
open(p, "w").writelines(good)
PY
}

newvm(){ # $1 = session name
  local made=0
  for hw in "--gpu A100 --high-mem" "--gpu A100"; do
    if timeout 600 colab new $hw -s "$1" < /dev/null >>"$LOG" 2>&1; then
      say "  got $hw"; made=1; break
    fi
    say "  unavailable: $hw"
  done
  [ "$made" = 1 ]
}

push(){ timeout 600 colab upload -s "$S" "$1" "$2" < /dev/null >>"$LOG" 2>&1 \
          || say "UPLOAD FAILED $1"; }

# ---------------- phase A: train ----------------
have_adapters(){
  for a in ${ARMS//,/ }; do
    [ "$a" = base ] && continue
    [ -s "$ADIR/adapter_$a/adapter_model.safetensors" ] || return 1
  done
  return 0
}

if have_adapters; then
  say "adapters already on disk, skipping training"
else
  # Phase A is attempted up to three times with a fresh VM each time. Everything here is
  # defensive for a reason found the hard way: the first full run read a STALE
  # txt1_remote.log left over from the smoke, saw TXT_STAGE1_DONE in it, and spent twenty
  # minutes "retrying the download" of adapters that had never been trained -- the launch
  # exec had died with "Connection was lost." and nothing was running at all.
  for attempt in 1 2 3; do
    have_adapters && break
    RLOG="$SP/log/txt1_remote.log"
    rm -f "$RLOG"                     # never let a previous run's log look like progress
    S="txttrain$attempt"
    say "=== phase A attempt $attempt: training (STEPS=$STEPS SEED=$SEED) ==="
    newvm "$S" || { say "  no VM; next attempt"; continue; }
    push .hf /content/hf_token.txt
    push scripts/vlm/txt_stage1.py /content/txt_stage1.py
    push scripts/vlm/launch_bg.py /content/launch_bg.py
    cat > "$SP/stage_txttrain.py" <<PY
import os, subprocess, sys
os.makedirs("/content/txt", exist_ok=True)
os.environ.update({"BG_SCRIPT": "/content/txt_stage1.py", "BG_LOG": "/content/txt1.log",
                   "STEPS": "${STEPS}", "SEED": "${SEED}", "ARMS": "af,db",
                   "N_TRAIN": "${N_TRAIN}"})
r = subprocess.run([sys.executable, "/content/launch_bg.py"], capture_output=True, text=True)
print(r.stdout, r.stderr[-800:], flush=True)
PY
    # the launch exec itself is the flaky step, so retry it on the same VM before giving up
    launched=0
    for try in 1 2 3; do
      timeout 300 colab exec -s "$S" --timeout 180 -f "$SP/stage_txttrain.py" \
        < /dev/null > "$SP/txttrain_exec.txt" 2>&1
      if grep -q LAUNCHED "$SP/txttrain_exec.txt"; then launched=1; break; fi
      say "  launch attempt $try failed: $(grep -oE 'RuntimeError.*' "$SP/txttrain_exec.txt" | head -1)"
      sleep 15
    done
    if [ "$launched" = 0 ]; then
      say "  could not launch training; next attempt"
      timeout 120 colab stop -s "$S" < /dev/null >>"$LOG" 2>&1
      continue
    fi
    say "  launched; polling for adapters"
    done_seen=0
    for poll in $(seq 1 30); do
      sleep 45
      timeout 120 colab download -s "$S" /content/txt1.log "$RLOG" \
        < /dev/null >/dev/null 2>&1
      grep -E "ABORT|Traceback|OutOfMemory" "$RLOG" 2>/dev/null | tail -2 | tee -a "$LOG"
      grep -E "^  step |SAVED|parts, md5" "$RLOG" 2>/dev/null | tail -1 | tee -a "$LOG"
      if ! grep -q "TXT_STAGE1_DONE" "$RLOG" 2>/dev/null; then continue; fi
      done_seen=$(( done_seen + 1 ))
      for a in af db; do
        [ -s "$ADIR/adapter_$a/adapter_model.safetensors" ] && continue
        mkdir -p "$ADIR/adapter_$a"
        timeout 120 colab download -s "$S" "/content/txt/aparts/adapter_$a.config.json" \
          "$ADIR/adapter_$a/adapter_config.json" < /dev/null >/dev/null 2>&1 || continue
        : > "$SP/ap_$a.bin"; ok=1
        for i in 00 01 02 03 04 05 06 07 08 09; do
          if timeout 240 colab download -s "$S" "/content/txt/aparts/adapter_$a.p$i" \
               "$SP/ap_${a}_$i" < /dev/null >/dev/null 2>&1; then
            cat "$SP/ap_${a}_$i" >> "$SP/ap_$a.bin"; rm -f "$SP/ap_${a}_$i"
          else
            [ "$i" = 00 ] && ok=0
            break
          fi
        done
        # The remote printed the md5 of the file it saved. Checking the reassembled download
        # against THAT is the only way a truncated transfer cannot pass: comparing a local
        # file with its own md5 proves nothing.
        want=$(grep -oE "adapter_$a: [0-9]+ parts, md5=[0-9a-f]+" "$RLOG" | tail -1 \
                 | sed "s/.*md5=//")
        got=$(md5sum "$SP/ap_$a.bin" 2>/dev/null | cut -d" " -f1)
        if [ "$ok" = 1 ] && [ -n "$want" ] && [ "$got" = "$want" ]; then
          mv "$SP/ap_$a.bin" "$ADIR/adapter_$a/adapter_model.safetensors"
          say "  adapter $a OK ($(stat -c%s "$ADIR/adapter_$a/adapter_model.safetensors") bytes, md5 ${want:0:12})"
        else
          rm -f "$SP/ap_$a.bin"
          say "  adapter $a transfer bad (want ${want:0:12} got ${got:0:12}); will retry"
        fi
      done
      have_adapters && { say "  both adapters downloaded"; break; }
      [ "$done_seen" -ge 6 ] && { say "  training done but adapters will not transfer"; break; }
    done
    timeout 120 colab stop -s "$S" < /dev/null >>"$LOG" 2>&1
  done
  have_adapters || { say "PHASE A FAILED -- no adapters"; exit 1; }
fi

MD5_AF=$(md5sum "$ADIR/adapter_af/adapter_model.safetensors" | cut -d" " -f1)
MD5_DB=$(md5sum "$ADIR/adapter_db/adapter_model.safetensors" | cut -d" " -f1)
say "adapters: af=${MD5_AF:0:12} db=${MD5_DB:0:12}"

# ---------------- phase B: generate ----------------
for cond in ${CONDS//,/ }; do
  # the outputs/vlm2_* prefix is what every analysis script globs (check_attempt.py,
  # audit_nonanswer.py, stats_protocol.py, ...), so the text-only run uses it too. It is a
  # directory convention, not a claim that this run involved a vision model.
  OUTDIR="outputs/vlm2_${cond}"; mkdir -p "$OUTDIR"
  EVAL_LOCAL="$SP/data/eval_harmful_${cond}.jsonl"
  N_EVAL=$(wc -l < "$EVAL_LOCAL")
  complete(){ for a in ${ARMS//,/ }; do
      [ "$(rows "$OUTDIR/res_${a}.jsonl")" -ge "$N_EVAL" ] || return 1; done; return 0; }

  for round in $(seq 1 "$ROUNDS"); do
    if complete; then say "$cond: all arms at $N_EVAL rows"; break; fi
    S="txtg${round}"
    tot=0; for a in ${ARMS//,/ }; do tot=$(( tot + $(rows "$OUTDIR/res_${a}.jsonl") )); done
    say "=== phase B $cond round $round (have $tot rows) ==="
    newvm "$S" || { sleep 60; continue; }
    push .hf /content/hf_token.txt
    push scripts/vlm/txt_gen.py /content/txt_gen.py
    push scripts/vlm/launch_bg.py /content/launch_bg.py
    # uploading into a directory that does not exist yet fails silently-ish (the contents
    # API 404s), which is what made the first smoke round upload nothing at all
    cat > "$SP/stage_txtdirs.py" <<'PYEOF'
import os
for d in ("/content/txt", "/content/txt/adapter_af", "/content/txt/adapter_db",
          "/content/txt/aparts_up"):
    os.makedirs(d, exist_ok=True)
print("DIRS_OK", flush=True)
PYEOF
    timeout 200 colab exec -s "$S" --timeout 120 -f "$SP/stage_txtdirs.py" \
      < /dev/null 2>&1 | grep -E "DIRS_OK|Error" | tee -a "$LOG" || true
    push "$EVAL_LOCAL" "/content/txt/eval_harmful_${cond}.jsonl"
    # ~160MB per adapter in 30MB parts, five at a time with one retry each: a single
    # transient failure here used to cost the whole round
    : > "$SP/upfail_txt"
    for a in af db; do
      push "$ADIR/adapter_$a/adapter_config.json" "/content/txt/adapter_$a/adapter_config.json"
      rm -f "$SP"/up_${a}_*
      split -b 30m -d -a 2 "$ADIR/adapter_$a/adapter_model.safetensors" "$SP/up_${a}_"
      for p in "$SP"/up_${a}_*; do
        ( timeout 600 colab upload -s "$S" "$p" "/content/txt/aparts_up/$(basename "$p")" \
            < /dev/null >/dev/null 2>&1 \
          || timeout 600 colab upload -s "$S" "$p" "/content/txt/aparts_up/$(basename "$p")" \
               < /dev/null >/dev/null 2>&1 \
          || echo "$(basename "$p")" >> "$SP/upfail_txt" ) &
        while [ "$(jobs -rp | wc -l)" -ge 5 ]; do sleep 1; done
      done
      wait
      rm -f "$SP"/up_${a}_*
    done
    if [ -s "$SP/upfail_txt" ]; then
      say "  PART UPLOADS FAILED: $(tr '\n' ' ' < "$SP/upfail_txt")"
    fi
    for a in ${ARMS//,/ }; do
      f="$OUTDIR/res_${a}.jsonl"
      [ -f "$f" ] && push "$f" "/content/txt/res_${a}.jsonl"
    done
    cat > "$SP/stage_txtgen.py" <<PY
import os, glob, hashlib, subprocess, sys
os.makedirs("/content/txt", exist_ok=True)
for a in ("af", "db"):
    parts = sorted(glob.glob("/content/txt/aparts_up/up_%s_*" % a))
    if parts:
        with open("/content/txt/adapter_%s/adapter_model.safetensors" % a, "wb") as fh:
            for p in parts:
                fh.write(open(p, "rb").read())
    f = "/content/txt/adapter_%s/adapter_model.safetensors" % a
    print(a, "md5", hashlib.md5(open(f, "rb").read()).hexdigest(), os.path.getsize(f),
          flush=True)
exp = {"af": "${MD5_AF}", "db": "${MD5_DB}"}
for a in ("af", "db"):
    f = "/content/txt/adapter_%s/adapter_model.safetensors" % a
    if hashlib.md5(open(f, "rb").read()).hexdigest() != exp[a]:
        print("MISMATCH", a, flush=True); sys.exit(1)
print("ADAPTERS_OK", flush=True)
os.environ.update({"BG_SCRIPT": "/content/txt_gen.py", "BG_LOG": "/content/txtgen.log",
                   "ARMS": "${ARMS}", "BS": "${BS}", "TIME_BUDGET": "${BUDGET}",
                   "EVALF": "/content/txt/eval_harmful_${cond}.jsonl", "SFX": ""})
r = subprocess.run([sys.executable, "/content/launch_bg.py"], capture_output=True, text=True)
print(r.stdout, r.stderr[-800:], flush=True)
PY
    timeout 300 colab exec -s "$S" --timeout 200 -f "$SP/stage_txtgen.py" \
      < /dev/null > "$SP/txtgen_exec.txt" 2>&1
    grep -E "ADAPTERS_OK|MISMATCH|LAUNCHED|md5|Error" "$SP/txtgen_exec.txt" \
      | tee -a "$LOG" || true
    if ! grep -q LAUNCHED "$SP/txtgen_exec.txt"; then
      say "  launch failed (adapters not assembled?); next round"
      timeout 120 colab stop -s "$S" < /dev/null >>"$LOG" 2>&1
      continue
    fi

    # same stale-log hazard as phase A: a TXT_MULTI_ left in this file by an earlier round
    # would end the poll before the new job had written a single row
    rm -f "$SP/log/txtgen_remote_${cond}.log"
    say "polling every 30s"
    stall=0
    while true; do
      sleep 30
      got=0
      for a in ${ARMS//,/ }; do
        timeout 120 colab download -s "$S" "/content/txt/res_${a}.jsonl" \
          "$OUTDIR/res_${a}.jsonl" < /dev/null >/dev/null 2>&1 && got=1
        trim "$OUTDIR/res_${a}.jsonl"
      done
      timeout 120 colab download -s "$S" /content/txtgen.log \
        "$SP/log/txtgen_remote_${cond}.log" < /dev/null >/dev/null 2>&1
      tot=0; for a in ${ARMS//,/ }; do tot=$(( tot + $(rows "$OUTDIR/res_${a}.jsonl") )); done
      say "  polled: total $tot rows$( [ "$got" = 0 ] && echo ' (nothing yet)')"
      if complete; then say "  all arms complete"; break; fi
      if [ "$got" = 0 ]; then stall=$(( stall + 1 )); else stall=0; fi
      [ "$stall" -ge 8 ] && { say "  session unreachable; next round"; break; }
      if grep -q "TXT_MULTI_" "$SP/log/txtgen_remote_${cond}.log" 2>/dev/null; then
        say "  remote job finished"; break
      fi
    done
    timeout 120 colab stop -s "$S" < /dev/null >>"$LOG" 2>&1
  done
  say "$cond FINAL:"
  for a in ${ARMS//,/ }; do say "  $a: $(rows "$OUTDIR/res_${a}.jsonl")/$N_EVAL"; done

  if [ -n "${SKIP_JUDGE:-}" ]; then say "$cond: judging skipped"; continue; fi
  if ! complete; then say "$cond: incomplete, not judging"; continue; fi
  for J in lg qg; do
    say "=== $cond: judge $J (raw protocol) ==="
    SP="$SP" SFX="_$cond" ARMS="$ARMS" JUDGE="$J" ROUNDS=8 BS=12 \
      bash scripts/vlm/run_v3_judge.sh 2>&1 | sed "s/^/[txt] /"
  done
  # the plain condition's prompt IS the request, so there is no request-free form of it
  case "$cond" in
    txtplain) say "$cond: request-free protocol not defined (prompt is the request)" ;;
    *) say "=== $cond: request-free protocol ==="
       SP="$SP" SFX="_$cond" ARMS="$ARMS" bash scripts/vlm/run_neutral_judge.sh 2>&1 \
         | sed "s/^/[txt] /" ;;
  esac
done
say "RUN_TXT_DONE"
